#pragma once

#include <stdexcept>
#include <vector>

class IBitReader {
public:
    virtual int ReadBit() = 0;
    virtual ~IBitReader() = default;
};

template <typename HuffValue>
class HuffmanDecoder {
public:
    void Init(const std::vector<int>& bits, std::vector<HuffValue> huff_val);
    const HuffValue& Decode(IBitReader& reader);

private:
    void GenerateDecoderTables(const std::vector<int>& bits, const std::vector<int>& huff_code);

    std::vector<HuffValue> huff_val_;
    std::vector<int> min_code_;
    std::vector<int> max_code_;
    std::vector<int> val_ptr_;

    bool is_initialized_ = false;
};

/*
Generates a table of Huffman code sizes for each value.

@param bits A vector, where bits[i] stores the number of Huffman codes of length i.

@return A vector huff_size, where huff_size[i] is the code size of huff_val[i].
*/
inline std::vector<int> GenerateSizeTable(const std::vector<int>& bits) {
    std::vector<int> huff_size;

    int values_count = 0;
    for (size_t i = 0; i < bits.size(); ++i) {
        values_count += bits[i];
    }
    huff_size.reserve(values_count);

    int count = 1;
    size_t size = 1;

    while (size < bits.size()) {
        if (count <= bits[size]) {
            huff_size.push_back(static_cast<int>(size));
            ++count;
        } else {
            ++size;
            count = 1;
        }
    }

    return huff_size;
}

/*
Generates a table of Huffman codes for each size in huff_size.

@param huff_size generated by the GenerateSizeTable.

@return A vector huff_code, where huff_code[i] is the numerical code of length huff_size[i].
*/
inline std::vector<int> GenerateCodeTable(const std::vector<int>& huff_size) {
    std::vector<int> huff_code;
    huff_code.reserve(huff_size.size());

    int code = 0;
    int size = 1;

    for (size_t k = 0; k < huff_size.size(); ++k) {
        while (size < huff_size[k]) {
            if (size >= 31) {
                throw std::runtime_error("Huffman code exceeds maximum length (31 bits)");
            }
            code <<= 1;
            ++size;
        }
        huff_code.push_back(code++);
    }

    return huff_code;
}

template <typename HuffValue>
void HuffmanDecoder<HuffValue>::Init(const std::vector<int>& bits,
                                     std::vector<HuffValue> huff_val) {
    huff_val_ = std::move(huff_val);
    auto huff_size = GenerateSizeTable(bits);
    auto huff_code = GenerateCodeTable(huff_size);
    GenerateDecoderTables(bits, huff_code);
    is_initialized_ = true;
}

template <typename HuffValue>
const HuffValue& HuffmanDecoder<HuffValue>::Decode(IBitReader& reader) {
    if (!is_initialized_) {
        throw std::runtime_error("Huffman decoder is not initialized");
    }

    int code = reader.ReadBit();
    size_t size = 1;

    while (code > max_code_[size]) {
        if (size >= 31) {
            throw std::runtime_error("Huffman code exceeds maximum length (31 bits)");
        }
        if (size + 1 >= max_code_.size()) {
            throw std::runtime_error("Huffman code length out of range");
        }
        code = (code << 1) | reader.ReadBit();
        ++size;
    }

    int ptr = val_ptr_[size] + (code - min_code_[size]);
    if (ptr < 0 || static_cast<size_t>(ptr) >= huff_val_.size()) {
        throw std::runtime_error("Huffman decode pointer out of bounds");
    }

    return huff_val_[ptr];
}

/*
Generates min_code, max_code and val_ptr tables.
*/
template <typename HuffValue>
void HuffmanDecoder<HuffValue>::GenerateDecoderTables(const std::vector<int>& bits,
                                                      const std::vector<int>& huff_code) {
    min_code_.assign(bits.size(), 0);
    max_code_.assign(bits.size(), -1);
    val_ptr_.assign(bits.size(), 0);

    int ptr = 0;

    for (size_t size = 1; size < bits.size(); ++size) {
        if (bits[size] != 0) {
            val_ptr_[size] = ptr;
            min_code_[size] = huff_code[ptr];
            ptr += bits[size] - 1;
            max_code_[size] = huff_code[ptr++];
        }
    }
}
